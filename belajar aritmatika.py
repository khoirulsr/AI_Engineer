#operasi aritmatika

a = 10
b = 3

hasil = a + b
print(a,'+',b, '=', hasil)

hasil = a - b
print(a,'-',b, '=', hasil)

hasil = a * b
print(a,'x',b, '=', hasil)

hasil = a / b
print(a,'/',b, '=', hasil)

#eksponen (pangkat)
hasil = a ** b
print(a,'**',b, '=', hasil)

#modulus (sisa pembagian)
hasil = a % b
print(a,'%',b, '=', hasil)

#floor division (bagi tapi double //)
hasil = a // b
print(a,'//',b, '=', hasil)

